// Helper to generate representative normalized audio waveform peaks with dots and spikes
function makeWaveform(seed: number, count = 64): number[] {
  const peaks: number[] = [];
  for (let i = 0; i < count; i++) {
    const isSpike = Math.sin((i + seed * 2) * 0.6) > 0.35 && (i % 3 !== 0);
    if (!isSpike) {
      peaks.push(0.02);
    } else {
      const raw = Math.sin((i + seed) * 0.8) * 0.4 + Math.cos((i * 1.5 + seed) * 0.4) * 0.4 + 0.35;
      const peak = Math.max(0.15, Math.min(0.95, Number(raw.toFixed(2))));
      peaks.push(peak);
    }
  }
  return peaks;
}

